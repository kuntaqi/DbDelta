using System.Text;
using System.Text.RegularExpressions;
using DbDelta.Core.Model;

namespace DbDelta.PostgreSql;

// Pure statement text, kept apart from the emitter the way TSqlWriter is on the SQL Server side. Everything
// here renders one object; the emitter decides which objects and in what phase. Identifiers go through the
// quoter; column defaults, check expressions and programmable bodies are reused verbatim because the reader
// took them from pg_get_expr / pg_get_*def, which already produce valid PostgreSQL.
internal static partial class PgStatementWriter
{
    private static readonly PostgreSqlQuoter Q = PostgreSqlQuoter.Instance;

    public static string CreateSchema(string schema) =>
        $"CREATE SCHEMA IF NOT EXISTS {Q.Quote(schema)};";

    public static string CreateTable(TableDefinition table)
    {
        var columns = table.Columns
            .OrderBy(c => c.OrdinalPosition)
            .Select(c => "    " + ColumnDefinition(c));

        return $"CREATE TABLE {Q.Qualify(table.Identity)} (\n{string.Join(",\n", columns)}\n);";
    }

    public static string ColumnDefinition(ColumnDefinition column)
    {
        var sql = new StringBuilder();
        sql.Append(Q.Quote(column.Name)).Append(' ').Append(PgTypeText.Declare(column.DataType));

        if (column.Collation is { } collation)
        {
            sql.Append(" COLLATE ").Append(Q.Quote(collation));
        }

        if (column.ComputedExpression is { } computed)
        {
            sql.Append(" GENERATED ALWAYS AS (").Append(computed).Append(") STORED");
        }
        else if (column.Identity is { } identity)
        {
            // The reader keeps seed and increment but not always-vs-by-default, so BY DEFAULT is used: it is
            // the less restrictive of the two and never rejects an insert the source would have allowed.
            sql.Append(" GENERATED BY DEFAULT AS IDENTITY");
            if (identity.Seed != 1 || identity.Increment != 1)
            {
                sql.Append(" (START WITH ").Append(identity.Seed)
                    .Append(" INCREMENT BY ").Append(identity.Increment).Append(')');
            }
        }
        else if (column.DefaultExpression is { } @default)
        {
            sql.Append(" DEFAULT ").Append(@default);
        }

        if (!column.IsNullable)
        {
            sql.Append(" NOT NULL");
        }

        return sql.ToString();
    }

    public static string AddPrimaryKey(ObjectIdentity table, PrimaryKeyDefinition pk) =>
        $"ALTER TABLE {Q.Qualify(table)} ADD CONSTRAINT {Q.Quote(pk.Name)} PRIMARY KEY ({KeyColumns(pk.Columns)});";

    public static string AddUniqueConstraint(ObjectIdentity table, UniqueConstraintDefinition unique) =>
        $"ALTER TABLE {Q.Qualify(table)} ADD CONSTRAINT {Q.Quote(unique.Name)} UNIQUE ({KeyColumns(unique.Columns)});";

    public static string AddCheckConstraint(ObjectIdentity table, CheckConstraintDefinition check) =>
        $"ALTER TABLE {Q.Qualify(table)} ADD CONSTRAINT {Q.Quote(check.Name)} CHECK {check.Expression};";

    public static string AddForeignKey(ObjectIdentity table, ForeignKeyDefinition fk)
    {
        var sql = new StringBuilder($"ALTER TABLE {Q.Qualify(table)} ADD CONSTRAINT {Q.Quote(fk.Name)} FOREIGN KEY (")
            .Append(Columns(fk.Columns)).Append(") REFERENCES ").Append(Q.Qualify(fk.ReferencedTable))
            .Append(" (").Append(Columns(fk.ReferencedColumns)).Append(')');

        if (PgTypeText.ReferentialAction(fk.OnDelete) is { } onDelete)
        {
            sql.Append(" ON DELETE ").Append(onDelete);
        }

        if (PgTypeText.ReferentialAction(fk.OnUpdate) is { } onUpdate)
        {
            sql.Append(" ON UPDATE ").Append(onUpdate);
        }

        return sql.Append(';').ToString();
    }

    public static string DropConstraint(ObjectIdentity table, string name) =>
        $"ALTER TABLE {Q.Qualify(table)} DROP CONSTRAINT {Q.Quote(name)};";

    public static string AddColumn(ObjectIdentity table, ColumnDefinition column) =>
        $"ALTER TABLE {Q.Qualify(table)} ADD COLUMN {ColumnDefinition(column)};";

    public static string DropColumn(ObjectIdentity table, string name) =>
        $"ALTER TABLE {Q.Qualify(table)} DROP COLUMN {Q.Quote(name)};";

    // PostgreSQL alters a column through independent sub-commands; each difference the caller found becomes one.
    public static string AlterColumnType(ObjectIdentity table, ColumnDefinition column) =>
        $"ALTER TABLE {Q.Qualify(table)} ALTER COLUMN {Q.Quote(column.Name)} TYPE {PgTypeText.Declare(column.DataType)};";

    public static string SetNotNull(ObjectIdentity table, string column, bool notNull) =>
        $"ALTER TABLE {Q.Qualify(table)} ALTER COLUMN {Q.Quote(column)} {(notNull ? "SET" : "DROP")} NOT NULL;";

    public static string SetDefault(ObjectIdentity table, ColumnDefinition column) =>
        column.DefaultExpression is { } expr
            ? $"ALTER TABLE {Q.Qualify(table)} ALTER COLUMN {Q.Quote(column.Name)} SET DEFAULT {expr};"
            : $"ALTER TABLE {Q.Qualify(table)} ALTER COLUMN {Q.Quote(column.Name)} DROP DEFAULT;";

    public static bool IsExpressionIndex(IndexDefinition index) =>
        index.Columns.Any(c => !PlainIdentifier().IsMatch(c.Name));

    public static string CreateIndex(ObjectIdentity table, IndexDefinition index)
    {
        var method = PgTypeText.IndexMethod(index.Kind);

        // DESC only means something to btree; the other access methods reject an ordering clause.
        var columns = string.Join(", ", index.Columns.Select(c =>
            index.Kind == IndexKind.Rowstore && c.IsDescending
                ? $"{Q.Quote(c.Name)} DESC"
                : Q.Quote(c.Name)));

        var sql = new StringBuilder("CREATE ")
            .Append(index.IsUnique ? "UNIQUE INDEX " : "INDEX ")
            .Append(Q.Quote(index.Name)).Append(" ON ").Append(Q.Qualify(table))
            .Append(" USING ").Append(method).Append(" (").Append(columns).Append(')');

        if (index.IncludedColumns.Count > 0)
        {
            sql.Append(" INCLUDE (").Append(Columns(index.IncludedColumns)).Append(')');
        }

        if (index.FilterExpression is { } predicate)
        {
            sql.Append(" WHERE ").Append(predicate);
        }

        return sql.Append(';').ToString();
    }

    public static string DropIndex(ObjectIdentity table, string name) =>
        // A PostgreSQL index is a schema object, dropped by its own qualified name, not through its table.
        $"DROP INDEX {Q.Quote(table.Schema)}.{Q.Quote(name)};";

    public static string DropTable(ObjectIdentity table) => $"DROP TABLE {Q.Qualify(table)};";

    public static string DropView(ObjectIdentity view, bool materialized) =>
        $"DROP {(materialized ? "MATERIALIZED VIEW" : "VIEW")} {Q.Qualify(view)};";

    public static string CreateView(ViewDefinition view, bool materialized) =>
        materialized
            ? $"CREATE MATERIALIZED VIEW {Q.Qualify(view.Identity)} AS\n{view.Definition};"
            : $"CREATE OR REPLACE VIEW {Q.Qualify(view.Identity)} AS\n{view.Definition};";

    // A routine's stored definition is a full CREATE OR REPLACE FUNCTION/PROCEDURE, reusable as-is.
    public static string CreateRoutine(RoutineDefinition routine) => EndWithSemicolon(routine.Definition);

    public static string DropRoutine(RoutineDefinition routine) =>
        // The identity name already carries the argument signature, which is how PostgreSQL disambiguates.
        $"DROP {(routine.Kind == RoutineKind.Procedure ? "PROCEDURE" : "FUNCTION")} "
        + $"{Q.Quote(routine.Identity.Schema)}.{routine.Identity.Name};";

    public static string CreateTrigger(TriggerDefinition trigger) => EndWithSemicolon(trigger.Definition);

    public static string DropTrigger(TriggerDefinition trigger, string triggerName) =>
        $"DROP TRIGGER {Q.Quote(triggerName)} ON {Q.Qualify(trigger.Table)};";

    private static string KeyColumns(IEnumerable<IndexColumn> columns) =>
        string.Join(", ", columns.Select(c => Q.Quote(c.Name)));

    private static string Columns(IEnumerable<string> columns) =>
        string.Join(", ", columns.Select(Q.Quote));

    private static string EndWithSemicolon(string sql) =>
        sql.TrimEnd().EndsWith(';') ? sql.TrimEnd() : sql.TrimEnd() + ";";

    [GeneratedRegex("^[a-z_][a-z0-9_$]*$")]
    private static partial Regex PlainIdentifier();
}
