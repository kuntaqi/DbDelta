using DbDelta.Core.Model;
using DbDelta.PostgreSql;

namespace DbDelta.PostgreSql.Tests;

// Exercises the reader against a real PostgreSQL. Skips when DBDELTA_PG_TEST is unset or unreachable, so the
// suite stays green on a machine without PostgreSQL while still being the only place the catalog SQL and the
// row folding meet a live server.
[Collection(nameof(PgCollection))]
[Trait("Speed", "Slow")]
[Trait("RequiresPostgres", "true")]
public sealed class PostgreSqlSchemaReaderTests
{
    private const string Schema = "dbdelta_rt";

    private const string Ddl = $"""
        drop schema if exists {Schema} cascade;
        create schema {Schema};

        create table {Schema}.parent (
            id          integer generated always as identity primary key,
            code        varchar(20) not null unique,
            created_at  timestamptz not null default now()
        );

        create table {Schema}.child (
            child_id    bigint generated by default as identity (start with 100 increment by 5),
            name        varchar(50) collate "C",
            notes       text,
            price       numeric(10,2) not null default 0,
            ratio       double precision,
            at_time     time(3),
            is_active   boolean not null default true,
            full_label  text generated always as (name || ':' || child_id::text) stored,
            parent_id   integer,
            constraint pk_child primary key (child_id),
            constraint uq_child_name unique (name),
            constraint ck_child_price check (price >= 0),
            constraint fk_child_parent foreign key (parent_id)
                references {Schema}.parent (id) on delete cascade on update no action
        );

        create index ix_child_name on {Schema}.child (name desc);
        create index ix_child_active on {Schema}.child (parent_id) where is_active;
        """;

    private readonly PgFixture _fixture;

    public PostgreSqlSchemaReaderTests(PgFixture fixture) => _fixture = fixture;

    [SkippableFact]
    public async Task Reads_tables_columns_keys_constraints_and_indexes()
    {
        Skip.IfNot(_fixture.Available, $"PostgreSQL is not available: {_fixture.UnavailableReason}");

        await _fixture.ExecuteAsync(Ddl);

        var schema = await new PostgreSqlSchemaReader(_fixture.ConnectionString!).ReadAsync();

        Assert.False(string.IsNullOrEmpty(schema.DatabaseName));
        Assert.Contains(schema.ReadWarnings, w => w.Contains("not read", StringComparison.Ordinal));

        var parent = Table(schema, "parent");
        var id = Column(parent, "id");
        Assert.Equal("integer", id.DataType.ToString());
        Assert.False(id.IsNullable);
        Assert.NotNull(id.Identity);
        Assert.Equal(1L, id.Identity!.Seed);
        Assert.Equal(1L, id.Identity.Increment);
        Assert.NotNull(parent.PrimaryKey);
        Assert.Equal(new[] { "id" }, parent.PrimaryKey!.Columns.Select(c => c.Name).ToArray());
        Assert.Contains(parent.UniqueConstraints, u => u.Columns.Any(c => c.Name == "code"));

        var child = Table(schema, "child");

        var childId = Column(child, "child_id");
        Assert.Equal("bigint", childId.DataType.ToString());
        Assert.Equal(100L, childId.Identity!.Seed);
        Assert.Equal(5L, childId.Identity.Increment);

        Assert.Equal("character varying(50)", Column(child, "name").DataType.ToString());
        Assert.Equal("C", Column(child, "name").Collation);
        Assert.True(Column(child, "name").IsNullable);
        Assert.Equal("numeric(10,2)", Column(child, "price").DataType.ToString());
        Assert.Equal("double precision", Column(child, "ratio").DataType.ToString());
        Assert.Equal("time without time zone(3)", Column(child, "at_time").DataType.ToString());
        Assert.Equal("boolean", Column(child, "is_active").DataType.ToString());

        var fullLabel = Column(child, "full_label");
        Assert.NotNull(fullLabel.ComputedExpression);
        Assert.Null(fullLabel.DefaultExpression);

        var price = Column(child, "price");
        Assert.NotNull(price.DefaultExpression);
        Assert.Null(price.ComputedExpression);

        Assert.Equal("pk_child", child.PrimaryKey!.Name);
        Assert.Equal(new[] { "child_id" }, child.PrimaryKey.Columns.Select(c => c.Name).ToArray());

        var fk = Assert.Single(child.ForeignKeys);
        Assert.Equal("fk_child_parent", fk.Name);
        Assert.Equal(new[] { "parent_id" }, fk.Columns.ToArray());
        Assert.Equal(new[] { "id" }, fk.ReferencedColumns.ToArray());
        Assert.Equal(Schema, fk.ReferencedTable.Schema);
        Assert.Equal("parent", fk.ReferencedTable.Name);
        Assert.Equal(ReferentialAction.Cascade, fk.OnDelete);
        Assert.Equal(ReferentialAction.NoAction, fk.OnUpdate);

        var check = Assert.Single(child.CheckConstraints);
        Assert.Equal("ck_child_price", check.Name);
        Assert.Contains("price", check.Expression, StringComparison.Ordinal);

        // Indexes backing pk_child and uq_child_name are modelled on the constraints, not here.
        Assert.DoesNotContain(child.Indexes, i => i.Name is "pk_child" or "uq_child_name");

        var byName = child.Indexes.Single(i => i.Name == "ix_child_name");
        var nameColumn = Assert.Single(byName.Columns);
        Assert.Equal("name", nameColumn.Name);
        Assert.True(nameColumn.IsDescending);
        Assert.Equal(IndexKind.Rowstore, byName.Kind);
        Assert.Equal("100", byName.Extras["FillFactor"]);

        var partial = child.Indexes.Single(i => i.Name == "ix_child_active");
        Assert.False(string.IsNullOrEmpty(partial.FilterExpression));

        await _fixture.ExecuteAsync($"drop schema if exists {Schema} cascade;");
    }

    private static TableDefinition Table(DatabaseSchema schema, string name) =>
        schema.Tables.Single(t => t.Identity.Schema == Schema && t.Identity.Name == name);

    private static ColumnDefinition Column(TableDefinition table, string name) =>
        table.Columns.Single(c => c.Name == name);
}
