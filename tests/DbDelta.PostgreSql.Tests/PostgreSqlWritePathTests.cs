using DbDelta.Core.Comparison;
using DbDelta.PostgreSql;

namespace DbDelta.PostgreSql.Tests;

// The write path's real proof: build a source and a target database that differ across every object kind the
// emitter handles, compare, emit, apply the script to the target with the real executor, then re-read the
// target and compare again. A correct emitter+executor makes the second comparison empty — the target now
// matches the source. Creates and drops two scratch databases, so it is slow and skips without a server.
[Collection(nameof(PgCollection))]
[Trait("Speed", "Slow")]
[Trait("RequiresPostgres", "true")]
public sealed class PostgreSqlWritePathTests
{
    private const string SourceDb = "dbdelta_wp_src";
    private const string TargetDb = "dbdelta_wp_tgt";

    private const string SourceDdl = """
        create schema app;

        create sequence app.order_no start with 5 increment by 2 minvalue 1 maxvalue 1000 cycle;
        create type app.mood as enum ('sad', 'ok', 'happy');
        create domain app.pos_int as integer not null check (value > 0);
        create type app.full_name as (first text, last text);

        create table app.parent (
            id   integer generated always as identity primary key,
            code varchar(20) not null unique
        );

        create table app.child (
            child_id  bigint generated by default as identity,
            name      varchar(50) collate "C",
            price     numeric(10,2) not null default 0,
            status    app.mood,
            tags      text[],
            label     text generated always as (name || '!') stored,
            parent_id integer,
            constraint pk_child primary key (child_id),
            constraint uq_child_name unique (name),
            constraint ck_child_price check (price >= 0),
            constraint fk_child_parent foreign key (parent_id)
                references app.parent (id) on delete cascade
        );

        create index ix_child_name on app.child (name);
        create index ix_child_tags on app.child using gin (tags);

        create table app.existing_both (
            id   integer primary key,
            name varchar(20),
            note text
        );

        create view app.active as select child_id, name from app.child;
        create materialized view app.cnt as select count(*) as n from app.child;
        create function app.combine(a integer, b integer) returns integer language sql as $$ select a + b $$;
        create function app.touch() returns trigger language plpgsql as $$ begin return new; end $$;
        create trigger trg_touch before update on app.child for each row execute function app.touch();
        """;

    // Diverges from the source: existing_both has a narrower name, an extra column and no note; legacy exists
    // only here. Everything else is absent, so the script must create it.
    private const string TargetDdl = """
        create schema app;

        create table app.existing_both (
            id    integer primary key,
            name  varchar(10),
            extra boolean
        );

        create table app.legacy (id integer primary key);
        """;

    private readonly PgFixture _fixture;

    public PostgreSqlWritePathTests(PgFixture fixture) => _fixture = fixture;

    [SkippableFact]
    public async Task Emits_and_applies_a_schema_sync_that_converges()
    {
        Skip.IfNot(_fixture.Available, $"PostgreSQL is not available: {_fixture.UnavailableReason}");

        await CreateDatabaseAsync(SourceDb);
        await CreateDatabaseAsync(TargetDb);

        try
        {
            var sourceConn = _fixture.ConnectionStringFor(SourceDb);
            var targetConn = _fixture.ConnectionStringFor(TargetDb);
            await PgFixture.ExecuteOnAsync(sourceConn, SourceDdl);
            await PgFixture.ExecuteOnAsync(targetConn, TargetDdl);

            var comparer = new SchemaComparer();

            var source = await new PostgreSqlSchemaReader(sourceConn).ReadAsync();
            var target = await new PostgreSqlSchemaReader(targetConn).ReadAsync();
            var diff = comparer.Compare(source, target);

            Assert.NotEmpty(diff.Differing);

            var script = new PostgreSqlScriptEmitter().Emit(source, target, diff);

            // The fixture is built to need no refusals: everything in it is a case the emitter handles.
            Assert.Empty(script.Refusals);

            var result = await new PostgreSqlScriptExecutor().ExecuteAsync(targetConn, script);
            Assert.True(result.Succeeded, result.ServerMessage ?? result.Message);

            // Re-read the target and compare again: a correct apply leaves nothing differing.
            var applied = await new PostgreSqlSchemaReader(targetConn).ReadAsync();
            var afterDiff = comparer.Compare(source, applied);

            Assert.Empty(afterDiff.Differing);
        }
        finally
        {
            await DropDatabaseAsync(SourceDb);
            await DropDatabaseAsync(TargetDb);
        }
    }

    private async Task CreateDatabaseAsync(string name)
    {
        await DropDatabaseAsync(name);
        await _fixture.ExecuteAsync($"create database {name}");
    }

    private async Task DropDatabaseAsync(string name)
    {
        try
        {
            await _fixture.ExecuteAsync($"drop database if exists {name} with (force)");
        }
        catch (Exception)
        {
            // Best-effort cleanup; a failure here must not mask the test's own result.
        }
    }
}
